library IEEE;
use IEEE.std_logic_1164.all;
use IEEE.numeric_std.all;

entity I_CACHE is
    port(
        pc    : in  std_logic_vector(31 downto 0);
        instr : out std_logic_vector(31 downto 0)
    );
end I_CACHE;

architecture behavior of I_CACHE is
    signal address : std_logic_vector(4 downto 0);
begin

    address <= pc(4 downto 0);

    process(address)
    begin
        case address is

            ------------------------------------------------------------------
            -- SCENARIO A: Forwarding (EX/MEM, MEM/WB)
            ------------------------------------------------------------------
            -- 0: addi $1, $0, 5
            when "00000" =>
                instr <= "00100000000000010000000000000101";

            -- 1: addi $2, $0, 10
            when "00001" =>
                instr <= "00100000000000100000000000001010";

            -- 2: add $3, $1, $2 (R3 = 5 + 10 = 15)
            when "00010" =>
                instr <= "00000000001000100001100000100000";

            -- 3: add $4, $3, $1 (R4 = 15 + 5 = 20)
            when "00011" =>
                instr <= "00000000011000010010000000100000";

            -- 4: sub $5, $4, $2 (R5 = 20 - 10 = 10)
            when "00100" =>
                instr <= "00000000100000100010100000100010";

            ------------------------------------------------------------------
            -- SCENARIO B: Load-use hazard (stall)
            ------------------------------------------------------------------
            -- 5: sw $5, 0($0) (10 -> Mem[0])
            when "00101" => 
                instr <= "10101100000001010000000000000000";

            -- 6: lw $6, 0($0) (R6 = Mem[0] = 10)
            when "00110" =>
                instr <= "10001100000001100000000000000000";

            -- 7: add $7, $6, $1 (R7 = 10 + 5 = 15)
            when "00111" =>
                instr <= "00000000110000010011100000100000";

            -- 8: add $8, $6, $2 (R8 = 10 + 10 = 20)
            when "01000" =>
                instr <= "00000000110000100100000000100000";

            ------------------------------------------------------------------
            -- SCENARIO C: Control hazards (flush)
            ------------------------------------------------------------------
            -- 9: beq $6, $5, +2   (taken because r6 == r5 -> skip PC10, PC11)
            when "01001" =>
                instr <= "00010000110001010000000000000010";

            -- 10: should be flushed if beq is taken
            when "01010" =>
                instr <= "00100000000010010000000000000001";
                -- addi r9, r0, 1 (R9 = 1)

            -- 11: should be flushed if beq is taken
            when "01011" =>
                instr <= "00100000000010010000000000000010";
                -- addi r9, r0, 2 (R9 = 2)

            -- 12: executes after taken branch
            when "01100" =>
                instr <= "00100000000010010000000000000011";
                -- addi r9, r0, 3 (R9 = 3)

            ------------------------------------------------------------------
            -- SCENARIO D: BLTZ (taken) + flush
            ------------------------------------------------------------------
            -- 13: addi $10, $0, -1 (R10 = -1)
            when "01101" =>
                instr <= "00100000000010101111111111111111";

            -- 14: bltz $10, +1   (taken -> skip PC15)
            when "01110" =>
                instr <= "00000101010000000000000000000001";

            -- 15: should be flushed if bltz is taken
            when "01111" =>
                instr <= "00100000000010110000000001100011";
                -- addi r11, r0, 99 (R11 = 99)

            -- 16: executes after bltz
            when "10000" =>
                instr <= "00100000000010110000000000011110";
                -- addi r11, r0, 30 (R11 = 30)

            ------------------------------------------------------------------
            -- SCENARIO E: Jump (flush following fetched instructions)
            ------------------------------------------------------------------
            -- 17: j 20  (skip PC18, PC19)
            when "10001" =>
                instr <= "00001000000000000000000000010100";
                -- j 20

            -- 18: should be flushed if jump works
            when "10010" =>
                instr <= "00100000000011000000000000000001";
                -- addi r12, r0, 1 (R12 = 1)

            -- 19: should be flushed if jump works
            when "10011" =>
                instr <= "00100000000011000000000000000010";
                -- addi r12, r0, 2 (R12 = 2)

            ------------------------------------------------------------------
            -- SCENARIO F: Overflow test
            ------------------------------------------------------------------
            -- 20: lui $13, 0x4000   (r13 = 0x4000_0000)
            when "10100" =>
                instr <= "00111100000011010100000000000000";

            -- 21: add $13, $13, $13 (overflow)
            when "10101" =>
                instr <= "00000001101011010110100000100000";

            -- 22: add $13, $13, $13 (overflow + zero)
            when "10110" =>
                instr <= "00000001101011010110100000100000";

            ------------------------------------------------------------------
            -- SCENARIO G: BNE not taken (fall-through correctness)
            ------------------------------------------------------------------
            -- 23: addi $14, $0, 7 (R14 = 7)
            when "10111" =>
                instr <= "00100000000011100000000000000111";

            -- 24: sw $14, 4($0) (7 -> Mem[4])
            when "11000" =>
                instr <= "10101100000011100000000000000100";

            -- 25: lw $15, 4($0) (R15 = Mem[4] = 7)
            when "11001" =>
                instr <= "10001100000011110000000000000100";

            -- 26: bne $15, $14, +1  (should NOT be taken because equal)
            when "11010" =>
                instr <= "00010101111011100000000000000001";

            -- 27: executes because bne not taken
            when "11011" =>
                instr <= "00100000000100000000000000010101";
                -- addi r16, r0, 21 (R16 = 21)

            ------------------------------------------------------------------
            -- SCENARIO H: BEQ taken (simple taken branch near end)
            ------------------------------------------------------------------
            -- 28: addi $17, $0, 0 (R17 = 0)
            when "11100" =>
                instr <= "00100000000100010000000000000000";

            -- 29: beq $17, $0, +1 (taken -> skip PC30)
            when "11101" =>
                instr <= "00010010001000000000000000000001";

            -- 30: should be flushed if beq taken
            when "11110" =>
                instr <= "00100000000100100000000000110111";
                -- addi r18, r0, 55 (R18 = 55)

            -- 31: NOP / end
            when "11111" =>
                instr <= (others => '0');

            ------------------------------------------------------------------
            -- Default: NOP
            ------------------------------------------------------------------
            when others =>
                instr <= (others => '0');  -- nop

        end case;
    end process;

end behavior;